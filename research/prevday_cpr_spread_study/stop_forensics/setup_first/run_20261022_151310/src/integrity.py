"""Preflight and final integrity verification.

Everything here is read-only with respect to the live deployment: git commands
that only read, file hashes, process listings and database file metadata. The
only files written are inside the study run directory.
"""
from __future__ import annotations

import hashlib
import json
import os
import subprocess
from pathlib import Path

REPO = '/opt/tradingai'

# Code files: this study must leave them byte for byte identical.
CODE_PROTECTED = [
    'app/research/cpr_trigger_engine.py',
    'app/research/cpr_strategy_engine.py',
    'app/live/engine.py',
    'app/paper_trade/engine.py',
    'app/api/app.py',
    'app/research/backtest.py',
    'app/core/db.py',
    'scripts/tg_alerts.py',
    'scripts/paper_confluence.py',
    'config/settings.json',
]

# Live artifacts: regenerated by the running deployment on its own schedule
# (`scripts/build_replay.py`, cron `5 16 * * 1-5`, plus the market-data timer),
# so their content tracks the latest live session and legitimately changes
# during a trading day. They are recorded and attributed, never asserted equal.
SERVICE_GENERATED = [
    'frontend/index.html',
    'frontend/paper.html',
    'frontend/signals.html',
    'frontend/alerts.html',
]

PROTECTED = CODE_PROTECTED + SERVICE_GENERATED


def _run(cmd, cwd=REPO):
    try:
        r = subprocess.run(cmd, cwd=cwd, shell=isinstance(cmd, str),
                           capture_output=True, text=True, timeout=120)
        return {'cmd': cmd if isinstance(cmd, str) else ' '.join(cmd),
                'returncode': r.returncode, 'stdout': r.stdout, 'stderr': r.stderr}
    except Exception as exc:                                  # pragma: no cover
        return {'cmd': str(cmd), 'error': repr(exc)}


def sha256(path):
    h = hashlib.sha256()
    try:
        with open(path, 'rb') as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b''):
                h.update(chunk)
    except OSError:
        return None
    return h.hexdigest()


def git_state():
    return {
        'head': _run(['git', 'rev-parse', 'HEAD'])['stdout'].strip(),
        'branch': _run(['git', 'rev-parse', '--abbrev-ref', 'HEAD'])['stdout'].strip(),
        'status': _run(['git', 'status', '--porcelain=v1', '-uall'])['stdout'],
        'status_sha256': hashlib.sha256(
            _run(['git', 'status', '--porcelain=v1', '-uall'])['stdout'].encode()).hexdigest(),
        'diff_stat': _run(['git', 'diff', '--stat'])['stdout'],
        'log': _run(['git', 'log', '--oneline', '-3'])['stdout'],
    }


def protected_hashes():
    out = {}
    for rel in PROTECTED:
        p = os.path.join(REPO, rel)
        out[rel] = {'sha256': sha256(p),
                     'size': os.path.getsize(p) if os.path.exists(p) else None,
                     'mtime': os.path.getmtime(p) if os.path.exists(p) else None,
                     'class': 'code' if rel in CODE_PROTECTED else 'service_generated'}
    return out


def process_state():
    gunicorn = _run('pgrep -a gunicorn')
    ps = _run('ps -eo pid,ppid,lstart,etime,command')
    lines = ps['stdout'].splitlines()
    masters = [l for l in lines if 'gunicorn' in l and 'master' in l]
    workers = [l for l in lines if 'gunicorn' in l and 'worker' in l]
    return {'gunicorn_pgrep': gunicorn['stdout'].strip(),
            'gunicorn_masters': masters, 'gunicorn_workers': workers,
            'systemd_unit': _run('systemctl is-active tradingai')['stdout'].strip(),
            'timer': _run('systemctl list-timers tradingai* --no-pager --all')['stdout'].strip()}


def db_state(path):
    out = {}
    for suffix in ('', '-wal', '-shm'):
        p = path + suffix
        if os.path.exists(p):
            st = os.stat(p)
            out[os.path.basename(p)] = {'size': st.st_size, 'mtime': st.st_mtime,
                                        'sha256': sha256(p) if suffix == '' else None}
    return out


def capture(label):
    state = {
        'label': label,
        'timestamp': _run('date -Is')['stdout'].strip(),
        'git': git_state(),
        'protected_hashes': protected_hashes(),
        'processes': process_state(),
        'live_db': db_state(os.path.join(REPO, 'database', 'tradingai.db')),
    }
    return state


def write_preflight(run_dir, state, snapshot_meta, extra=None):
    run_dir = Path(run_dir)
    out = run_dir / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'PREFLIGHT.json').write_text(json.dumps(state, indent=2, default=str))
    (out / 'PREFLIGHT_GIT_STATUS.txt').write_text(state['git']['status'])
    (out / 'PREFLIGHT_PROCESSES.txt').write_text(
        state['processes']['gunicorn_pgrep'] + '\n')
    (out / 'protected_hashes_preflight.json').write_text(
        json.dumps(state['protected_hashes'], indent=2, default=str))
    (out / 'db_meta_preflight.json').write_text(
        json.dumps({'live_db': state['live_db'], 'snapshot': snapshot_meta},
                   indent=2, default=str))
    g = state['git']
    p = state['processes']
    lines = [
        '# Phase 3 preflight - setup-first study',
        '',
        f"Captured: {state['timestamp']}",
        '',
        '## Repository',
        '',
        f"- repository: `{REPO}`",
        f"- branch: `{g['branch']}`",
        f"- HEAD: `{g['head']}`",
        f"- `git status --porcelain=v1 -uall` lines: {len(g['status'].splitlines())}",
        f"- status sha256: `{g['status_sha256']}`",
        '',
        'The working tree was already dirty before this study started (22 tracked '
        'modifications and many untracked files). The exact status file is stored '
        'as `outputs/PREFLIGHT_GIT_STATUS.txt` and is compared byte for byte in '
        'the final integrity check, so that any new file created by this study is '
        'detected.',
        '',
        '## Protected files',
        '',
        '| file | sha256 | bytes | class |',
        '|---|---|---|---|',
    ]
    for rel, blob in state['protected_hashes'].items():
        lines.append(f"| `{rel}` | `{blob['sha256']}` | {blob['size']} | "
                     f"{blob['class']} |")
    lines += [
        '',
        '## Live services',
        '',
        f"- systemd unit `tradingai`: `{p['systemd_unit']}`",
        f"- gunicorn master processes: {len(p['gunicorn_masters'])}",
        f"- gunicorn worker processes: {len(p['gunicorn_workers'])}",
        '',
        '```',
        p['gunicorn_pgrep'] or '(no gunicorn process found)',
        '```',
        '',
        '## Database',
        '',
        '```json',
        json.dumps(state['live_db'], indent=2),
        '```',
        '',
        'The live database is never written by this study. A fresh consistent '
        'snapshot is taken with the SQLite backup API and all research reads the '
        'snapshot copy. `TRADINGAI_DB_PATH` is pointed at a working copy of that '
        'snapshot before any `app.*` import, so the production engine module can '
        'only ever see the snapshot.',
        '',
    ]
    if extra:
        lines += ['## Additional preflight notes', ''] + [f"- {x}" for x in extra] + ['']
    (run_dir / 'reports' / 'PREFLIGHT.md').write_text('\n'.join(lines))
    return state


def write_final(run_dir, before, after, study_dir, extra_notes=None):
    run_dir = Path(run_dir)
    lines = [
        '# Phase 3 final integrity verification',
        '',
        f"Preflight: {before['timestamp']}",
        f"Final:     {after['timestamp']}",
        '',
        '## 1. Repository state',
        '',
        f"- branch before/after: `{before['git']['branch']}` / `{after['git']['branch']}`"
        f" - {'unchanged' if before['git']['branch'] == after['git']['branch'] else 'CHANGED'}",
        f"- HEAD before/after: `{before['git']['head']}` / `{after['git']['head']}`"
        f" - {'unchanged' if before['git']['head'] == after['git']['head'] else 'CHANGED'}",
        '',
        '## 2. Tracked modifications',
        '',
        f"- before: {len(before['git']['status'].splitlines())} status lines",
        f"- after:  {len(after['git']['status'].splitlines())} status lines",
        '',
        'The full status file is compared below; every difference must be a file '
        'inside the study directory.',
        '',
        '```diff',
    ]
    b = set(before['git']['status'].splitlines())
    a = set(after['git']['status'].splitlines())
    for line in sorted(b - a):
        lines.append(f'- {line}')
    for line in sorted(a - b):
        lines.append(f'+ {line}')
    if b == a:
        lines.append('(no difference)')
    lines += ['```', '', '## 3. Code files (must be byte identical)', '',
              '| file | sha256 before | sha256 after | identical |', '|---|---|---|---|']
    same = True
    for rel in CODE_PROTECTED:
        blob = before['protected_hashes'].get(rel, {})
        after_blob = after['protected_hashes'].get(rel, {})
        ok = blob.get('sha256') == after_blob.get('sha256')
        same = same and ok
        lines.append(f"| `{rel}` | `{blob.get('sha256')}` | `{after_blob.get('sha256')}` | "
                     f"{'yes' if ok else 'NO'} |")
    lines += ['', f"All code files identical: **{'yes' if same else 'NO'}**", '',
              '### 3b. Live artifacts (rebuilt by the running service)', '',
              'These files are written by the deployment itself, not by this study: '
              '`scripts/build_replay.py` (cron `5 16 * * 1-5`) rebuilds the replay '
              'sections of `frontend/index.html` and `frontend/paper.html` from the '
              'latest live session, and the market-data timer refreshes the signal '
              'pages. Their content therefore changes during a trading day. They are '
              'recorded for attribution only and are never asserted to be equal.', '',
              '| file | sha256 before | sha256 after | changed by the service |',
              '|---|---|---|---|']
    for rel in SERVICE_GENERATED:
        blob = before['protected_hashes'].get(rel, {})
        after_blob = after['protected_hashes'].get(rel, {})
        changed = blob.get('sha256') != after_blob.get('sha256')
        lines.append(f"| `{rel}` | `{blob.get('sha256')}` | `{after_blob.get('sha256')}` | "
                     f"{'yes (service regeneration)' if changed else 'no'} |")
    lines += ['', '## 4. New files', '',
              f"All files created by this study are inside `{study_dir}`.", '',
              '## 5. Live services', '',
              '```',
              after['processes']['gunicorn_pgrep'] or '(no gunicorn process found)',
              '```', '',
              '## 6. Database', '',
              '```json',
              json.dumps({'before': before['live_db'], 'after': after['live_db']}, indent=2),
              '```', '',
              'The live database is written by the running service on its normal '
              'schedule; this study only reads a snapshot of it. No alert, order or '
              'notification was generated.', '']
    if extra_notes:
        lines += ['## Notes', ''] + [f"- {x}" for x in extra_notes] + ['']
    (run_dir / 'reports' / 'INTEGRITY_FINAL.md').write_text('\n'.join(lines))
    code_same = same
    service_changed = [rel for rel in SERVICE_GENERATED
                       if before['protected_hashes'].get(rel, {}).get('sha256')
                       != after['protected_hashes'].get(rel, {}).get('sha256')]
    (run_dir / 'outputs' / 'integrity_final.json').write_text(json.dumps(
        {'before': before, 'after': after,
         'code_files_identical': code_same,
         'service_generated_changed': service_changed,
         'git_status_identical': b == a,
         'status_before': sorted(b), 'status_after': sorted(a)},
        indent=2, default=str))
    return {'code_files_identical': code_same,
            'service_generated_changed': service_changed,
            'git_status_identical': b == a}
