#!/usr/bin/env python3
"""Read-only LLM-assisted learning report: WHY the loss buckets happen.

Every number is deterministic. They come from the learned loss-memory
(scripts/loss_memory.build_memory over the paper_align book) plus the decay
file and the rule registry. The LLM ONLY turns those exact numbers into
plain-English prose. It never gates, sizes, ranks or picks trades, and it may
not invent any statistic beyond the JSON it is handed. With no LLM key (or
--no-llm) the report is fully deterministic.

Read-only: SELECTs only. Writes only reports/learning_report_<date>.md.
Never touches DB rows, engine, trigger, alert or frontend code.

  cd /opt/tradingai && python3 scripts/learning_report.py            # deterministic
  cd /opt/tradingai && python3 scripts/learning_report.py --llm      # + narrative
"""
import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.request
from collections import defaultdict
from datetime import datetime
from zoneinfo import ZoneInfo

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if BASE not in sys.path:
    sys.path.insert(0, BASE)
if os.path.join(BASE, 'scripts') not in sys.path:
    sys.path.insert(0, os.path.join(BASE, 'scripts'))

import loss_memory as lm  # noqa: E402
from app.core.db import get_conn  # noqa: E402

IST = ZoneInfo('Asia/Kolkata')
REPORTS = os.path.join(BASE, 'reports')
DIMS = ('instrument_id', 'direction', 'level', 'regime', 'dow', 'vix_dir')


def _stats(rows):
    n = len(rows)
    wins = sum(1 for x in rows if x['result'] == 'WIN')
    tot = round(sum(x['r'] for x in rows), 2)
    return {'n': n, 'wins': wins, 'losses': n - wins,
            'wr': round(wins / n, 4) if n else 0.0, 'total_r': tot}


def collect_facts(engine='plain'):
    """Deterministic facts only. No LLM here. Read-only."""
    mem = lm.load_memory(engine) or {}
    conn = get_conn()
    try:
        raw = conn.execute(
            "SELECT session_date, instrument_id, direction, level, entry_time,"
            " r_multiple, result FROM paper_align WHERE variant=? AND state='SIGNAL'"
            " AND result IN ('WIN','LOSS') AND r_multiple IS NOT NULL"
            " ORDER BY session_date", (engine,)).fetchall()
        recs = []
        for r in raw:
            fp = lm.fingerprint_book(conn, r)
            fp['r'] = float(r['r_multiple'] or 0.0)
            fp['result'] = r['result']
            recs.append(fp)
        registry = []
        try:
            cols = [c[1] for c in conn.execute("PRAGMA table_info(rule_registry)")]
            if cols:
                registry = [dict(zip(cols, row)) for row in
                            conn.execute("SELECT * FROM rule_registry")]
        except Exception:
            registry = []
    finally:
        try:
            conn.close()
        except Exception:
            pass

    breakdown = {}
    for dim in DIMS:
        groups = defaultdict(list)
        for rec in recs:
            v = rec.get(dim)
            if v is None:
                continue
            groups[v].append(rec)
        breakdown[dim] = sorted(
            ({'value': v, **_stats(g)} for v, g in groups.items()),
            key=lambda x: x['total_r'])

    decay = lm.load_decay()
    return {
        'engine': engine,
        'as_of': datetime.now(IST).date().isoformat(),
        'book': _stats(recs),
        'trained_trades': mem.get('trained_trades'),
        'learned_rules': mem.get('rules', []),
        'registry': registry,
        'suppressed': decay.get('suppressed', []),
        'breakdown': breakdown,
    }


def _pct(x):
    return '%5.1f%%' % (100.0 * x)


def _rule_line(r):
    kd = ', '.join('%s=%s' % (k, v) for k, v in (r.get('keys') or {}).items())
    return ('| `%s` | %d | %dW/%dL | %s | %+.2fR | %s |'
            % (kd, r.get('n', 0), r.get('wins', 0), r.get('losses', 0),
               _pct(r.get('win_rate', 0.0)), r.get('total_r', 0.0),
               r.get('reason', '')))


def render_deterministic(f):
    L = []
    A = L.append
    A('# Learning report: why the loss buckets happen')
    A('')
    A('> Generated by `scripts/learning_report.py` (read-only). Numbers are '
      'deterministic (paper_align book + learned loss-memory + decay + rule '
      'registry). This is the "self-learn" layer: it flags setups with negative '
      'expectancy so they can be studied or skipped. Hypothetical; no advice; '
      'no prediction.')
    A('')
    b = f['book']
    A('## The book')
    A('')
    A('| Engine | Sessions (signals) | Win rate | Total R | Trained trades |')
    A('|---|---|---|---|---|')
    A('| %s | %d | %s | %+.2fR | %s |'
      % (f['engine'], b['n'], _pct(b['wr']), b['total_r'], f['trained_trades']))
    A('')
    A('A loss is a *bucket*, not a story: the learner slices every trade by '
      '`instrument_id, direction, level, regime (CPR width), dow, vix_dir` and '
      'flags any slice whose combined R is negative.')
    A('')

    A('## Learned avoid-rules (the loss buckets)')
    A('')
    rules = f['learned_rules']
    if rules:
        A('| Slice | n | W/L | Win rate | Total R | Reason |')
        A('|---|---|---|---|---|---|')
        for r in rules:
            A(_rule_line(r))
    else:
        A('_No avoid-rule currently meets the thresholds._')
    A('')

    A('## Breakdown by dimension (sorted worst-R first)')
    A('')
    for dim in DIMS:
        rows = f['breakdown'].get(dim) or []
        if not rows:
            continue
        A('### %s' % dim)
        A('')
        A('| Value | n | W/L | Win rate | Total R |')
        A('|---|---|---|---|---|')
        for r in rows:
            A('| %s | %d | %dW/%dL | %s | %+.2fR |'
              % (r['value'], r['n'], r['wins'], r['losses'], _pct(r['wr']), r['total_r']))
        A('')

    A('## Promoted / suppressed state')
    A('')
    if f['registry']:
        A('| Rule | Status | n | W/L | Win rate | Total R |')
        A('|---|---|---|---|---|---|')
        for r in f['registry']:
            A('| `%s` | %s | %s | %sW/%sL | %s | %sR |'
              % (r.get('keys_json', ''), r.get('status', ''),
                 r.get('n', ''), r.get('wins', ''), r.get('losses', ''),
                 _pct(r.get('win_rate', 0.0) or 0.0), r.get('total_r', '')))
    else:
        A('_Rule registry is empty._')
    A('')
    if f['suppressed']:
        A('Suppressed by decay (demoted, no longer enforced):')
        A('')
        for r in f['suppressed']:
            A('- `%s` — decay=%s, accuracy=%s, net_r=%+.2f (over %s veto rows)'
              % (json.dumps(r.get('keys', {})), r.get('decay', ''),
                 _pct(r.get('accuracy', 0.0) or 0.0), r.get('net_r', 0.0) or 0.0,
                 r.get('veto_rows', '?')))
        A('')
    A('---')
    A('')
    A('<sub>Deterministic layer of the self-learn pipeline. No recommendation.</sub>')
    return '\n'.join(L)


PROMPT = (
    "You are a quantitative research assistant writing an internal, read-only "
    "note that explains WHY certain setup buckets in an NSE index CPR-trigger "
    "log lose money. You are given a JSON of deterministic statistics only. "
    "RULES: use ONLY the numbers in the JSON; never invent, extend, project or "
    "estimate any value; never predict; never give trading advice or a "
    "recommendation. Explain the patterns plainly: which buckets carry the "
    "losses, how the loss is distributed (win rate vs R, sample size, recent vs "
    "all), what the learned rules and their promotion/suppression state mean, "
    "and the honest caveats (small samples, in-sample vs out-of-sample, bucket "
    "drift). Keep it tight; do not restate the tables verbatim. Output Markdown "
    "with a `## Analysis` heading and short paragraphs or bullets, 150-260 words."
)


def api_key():
    k = os.environ.get('LLM_API_KEY') or os.environ.get('GROQ_API_KEY')
    if not k:
        try:
            k = open(os.path.join(BASE, 'config', 'llm_key')).read().strip() or None
        except OSError:
            k = None
    return k


def llm_meta():
    base = os.environ.get('LLM_API_URL') or os.environ.get('LLM_BASE_URL')
    model = os.environ.get('LLM_MODEL')
    if base:
        if not model and 'mistral.ai' in base:
            model = 'mistral-small-latest'
        return base, model or 'mistral-small-latest'
    try:
        ai = json.load(open(os.path.join(BASE, 'config', 'settings.json')))['ai']
        prov, mdl = ai.get('provider', 'groq'), (ai.get('model') or 'mixtral')
    except Exception:
        prov, mdl = 'groq', 'mixtral'
    base = 'https://api.groq.com/openai/v1/chat/completions'
    model = {'mixtral': 'qwen/qwen3.8-27b'}.get(mdl, mdl)
    return base, model


def llm_narrate(facts):
    base, model = llm_meta()
    key = api_key()
    if not key:
        print('llm: no key (set LLM_API_KEY or config/llm_key); deterministic only',
              flush=True)
        return None
    payload = {'model': model, 'temperature': 0.4, 'max_tokens': 900,
               'messages': [{'role': 'system', 'content': PROMPT},
                            {'role': 'user', 'content': json.dumps(facts, indent=1)}]}
    ua = {'User-Agent': 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 '
                        '(KHTML, like Gecko) Chrome/120 Safari/537.36',
          'Accept': 'application/json, text/plain, */*'}
    deadline = time.time() + 45
    attempt = 0
    while time.time() < deadline:
        attempt += 1
        req = urllib.request.Request(
            base, data=json.dumps(payload).encode(),
            headers={'Authorization': 'Bearer %s' % key,
                     'Content-Type': 'application/json', **ua})
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                out = json.load(r)
            txt = (out.get('choices') or [{}])[0].get('message', {}).get('content') or ''
            if txt:
                return txt.strip()
            print('llm_empty model=%s' % model, flush=True)
            return None
        except urllib.error.HTTPError as e:
            if e.code in (429, 500, 502, 503, 529) and attempt < 4:
                print('llm_retry code=%s attempt=%d' % (e.code, attempt), flush=True)
                time.sleep(min(10, 3 * attempt))
                continue
            print('llm_fail code=%s (rate-limited/exhausted); falling back'
                  % e.code, flush=True)
            return None
        except (urllib.error.URLError, OSError, KeyError, ValueError,
                json.JSONDecodeError) as e:
            print('llm_fail %s' % type(e).__name__, flush=True)
            return None
    print('llm_quota_exhausted model=%s' % model, flush=True)
    return None


def main():
    ap = argparse.ArgumentParser(description='read-only learning report')
    ap.add_argument('--engine', default='plain', help='plain (default)')
    ap.add_argument('--llm', action='store_true', help='add LLM-drafted analysis')
    ap.add_argument('--out', default=None, help='output path (default reports/)')
    a = ap.parse_args()

    facts = collect_facts(a.engine)
    md = render_deterministic(facts)

    if a.llm:
        narrative = llm_narrate(facts)
        if narrative:
            md += '\n\n' + narrative.strip() + '\n\n<sub>Analysis drafted by an LLM '
            md += 'from the deterministic table above. Read-only; no advice.</sub>\n'
        else:
            md += ('\n\n## Analysis\n\n_LLM narration unavailable (no key or '
                   'request failed); deterministic tables above are authoritative._\n')

    os.makedirs(REPORTS, exist_ok=True)
    out = a.out or os.path.join(
        REPORTS, 'learning_report_%s.md' % datetime.now(IST).strftime('%Y-%m-%d'))
    with open(out, 'w') as fh:
        fh.write(md)
    print('wrote %s (%d bytes)' % (out, len(md)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
