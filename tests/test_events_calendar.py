"""Scheduled events calendar + advisory event-risk overlay.

Pure-module tests (no network, no DB) plus one endpoint smoke test. The
calendar is a reference layer: it must never fabricate an event, must resolve
after-close events to the next NSE session, and must fail safe (risk NONE) for
unknown instruments / empty coverage. Recurring events (monthly + weekly NSE
expiry, US payrolls) are generated by rule, so they must stay correct without
any per-month hand maintenance.
"""
from datetime import date, datetime, timedelta
from zoneinfo import ZoneInfo

from app.market import events_calendar as ec

IST = ZoneInfo('Asia/Kolkata')


def _dt(s):
    return datetime.fromisoformat(s).replace(tzinfo=IST)


def test_all_events_wellformed_and_sorted():
    evs = ec.all_events()
    assert evs, 'curated table must not be empty'
    keys = [(e['date'], e.get('time') or '') for e in evs]
    assert keys == sorted(keys), 'events must be sorted by (date, time)'
    for e in evs:
        assert e['impact'] in ('HIGH', 'MEDIUM', 'LOW')
        assert e['timing'] in ('INTRADAY', 'AFTER_CLOSE')
        assert e['bias'] in ('VOLATILITY', 'BEARISH_RISK', 'BULLISH_RISK', 'NEUTRAL')
        assert set(e['instruments']) <= {'NIFTY', 'BANKNIFTY', 'INDIA_VIX'}
        assert isinstance(e['approx'], bool)
        assert e.get('source')
        datetime.fromisoformat(e['date'])  # valid ISO date


def test_upcoming_filters_window_and_unknown_instrument():
    now = _dt('2026-10-17T10:00:00')
    up = ec.upcoming_events(now=now, days=30, instrument='NIFTY')
    assert up and all(x['date'] >= '2026-10-17' for x in up)
    assert ec.upcoming_events(now=now, days=30, instrument='NOPE') == []
    # INDIA_VIX only sees events that list it (fewer than NIFTY)
    vix = ec.upcoming_events(now=now, days=90, instrument='INDIA_VIX')
    nif = ec.upcoming_events(now=now, days=90, instrument='NIFTY')
    assert len(vix) <= len(nif)


def test_after_close_lands_next_session():
    # FOMC 2026-10-28 is after the NSE close -> impact lands on 2026-10-29.
    ev = [e for e in ec.all_events()
          if e['date'] == '2026-10-28' and e['category'] == 'MONETARY_POLICY'][0]
    assert ec._lands_on(ev).isoformat() == '2026-10-29'
    # An intraday event lands on its own session (Oct 2026 monthly expiry).
    exp = [e for e in ec.all_events()
           if e['date'] == '2026-10-27' and e['category'] == 'EXPIRY'][0]
    assert ec._lands_on(exp).isoformat() == '2026-10-27'


def test_event_risk_high_ahead_of_fomc():
    r = ec.event_risk('NIFTY', now=_dt('2026-10-27T11:00:00'))
    assert r['risk_level'] == 'HIGH'
    assert r['confirmation_required'] is True
    assert 'EVENT_CONFIRM_REQUIRED' in r['reasons']


def test_event_risk_high_on_impact_session():
    # On 2026-10-29 the after-close FOMC impact lands.
    r = ec.event_risk('NIFTY', now=_dt('2026-10-29T11:00:00'))
    assert r['risk_level'] == 'HIGH'
    assert any(e['name'].startswith('US Fed') for e in r['today_impact'])


def test_event_risk_none_or_low_when_events_far():
    r = ec.event_risk('NIFTY', now=_dt('2026-10-19T11:00:00'))
    assert r['risk_level'] in ('LOW', 'NONE')


def test_unknown_instrument_fails_safe():
    r = ec.event_risk('FOO')
    assert r['risk_level'] == 'NONE'
    assert r['confirmation_required'] is False
    assert r['today_impact'] == [] and r['pending'] == []


def test_coverage_markers_present():
    assert ec.COVERAGE_START and ec.COVERAGE_END and ec.CALENDAR_LAST_VERIFIED
    assert ec.COVERAGE_START <= ec.CALENDAR_LAST_VERIFIED <= ec.COVERAGE_END
    assert ec.HAND_ENCODED_END and ec.RECURRING_END
    assert ec.HAND_ENCODED_END <= ec.RECURRING_END


def test_monthly_expiry_is_last_tuesday_or_prior_session():
    now = _dt('2026-10-17T10:00:00')
    monthly = [e for e in ec.upcoming_events(now=now, days=120)
               if e['category'] == 'EXPIRY' and e['series'] == 'MONTHLY']
    assert monthly, 'monthly expiry must be generated'
    for e in monthly:
        assert e['recurring'] is True
        assert set(e['instruments']) == {'NIFTY', 'BANKNIFTY'}
        d = date.fromisoformat(e['date'])
        last_tue = ec._last_weekday(d.year, d.month, 1)
        assert d.weekday() < 5
        # on the month's last Tuesday, or shifted back within a week of it
        assert 0 <= (last_tue - d).days <= 6


def test_weekly_expiry_is_every_tuesday():
    now = _dt('2026-10-17T10:00:00')
    weekly = [e for e in ec.upcoming_events(now=now, days=90)
              if e['category'] == 'EXPIRY' and e['series'] == 'WEEKLY']
    assert weekly, 'weekly Nifty expiry must be generated'
    dates = sorted(date.fromisoformat(e['date']) for e in weekly)
    for e in weekly:
        assert set(e['instruments']) == {'NIFTY'}
        assert e['recurring'] is True
        assert date.fromisoformat(e['date']).weekday() < 5  # Tue, or shifted back
    # roughly one per week; a gap can widen to ~15 days when a weekly
    # coincides with (and is deduped into) that month's monthly expiry.
    assert all((b - a).days <= 15 for a, b in zip(dates, dates[1:]))


def test_monthly_and_weekly_known_dates():
    by = {}
    for e in ec.all_events():
        if e['category'] == 'EXPIRY':
            by.setdefault(e['date'], []).append(e['series'])
    # Oct 2026: monthly last Tuesday = 27 Oct (a session)
    assert 'MONTHLY' in by['2026-10-27']
    # Nov 2026: last Tuesday 24 Nov is Guru Nanak Jayanti -> previous session 23 Nov
    assert 'MONTHLY' in by['2026-11-23']
    # Dec 2026 monthly last Tuesday
    assert 'MONTHLY' in by['2026-12-29']
    # Oct 20 2026 (Tue) is a holiday -> that week's weekly shifts to Mon 19 Oct
    assert 'WEEKLY' in by['2026-10-19']
    # the monthly date must not also carry a weekly entry (deduped)
    assert 'WEEKLY' not in by['2026-10-27']


def test_recurring_nfp_first_friday_and_january_shift():
    by_date = {e['date']: e for e in ec.all_events()
               if e['category'] == 'EMPLOYMENT'}
    for iso, e in by_date.items():
        assert e['recurring'] is True
        assert date.fromisoformat(iso).weekday() == 4  # Friday
        assert int(iso[8:10]) <= 8  # first week (never the 1st when shifted)
    # 2027-01-01 is New Year -> payrolls shift to the following Friday.
    assert '2027-01-08' in by_date
    assert '2026-11-06' in by_date  # first Friday of Nov 2026


def test_recurring_generation_extends_beyond_hand_encoded():
    hand_dates = {e['date'] for e in ec.EVENTS}
    all_dates = {e['date'] for e in ec.all_events()}
    assert all_dates - hand_dates, 'recurring generation must add events'
    assert any(e['recurring'] for e in ec.all_events())
    assert max(date.fromisoformat(d) for d in all_dates) > date.fromisoformat(
        ec.HAND_ENCODED_END), 'recurring window must extend past hand table'


def test_endpoint_smoke():
    from app.api.app import app
    c = app.test_client()
    r = c.get('/api/market/events?days=120')
    assert r.status_code == 200
    d = r.get_json()['data']
    assert isinstance(d['events'], list) and d['events']
    assert 'risk' in d and 'NIFTY' in d['risk'] and 'BANKNIFTY' in d['risk']
    assert d['coverage']['end']
    assert d['coverage'].get('hand_encoded_end')
    bad = c.get('/api/market/events?instrument=FOO')
    assert bad.status_code == 400
    assert bad.get_json()['data']['reasons'] == ['UNKNOWN_INSTRUMENT']
